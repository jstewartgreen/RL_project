"""## 2.6 Interface notes for the model and PPO code
**Everything is derived from `make_env(ENV_CFG, stack=True)`**, so if `EnvConfig` changes (frame stack, resolution, game, ...) the buffer adapts. Nothing in the dataset code hard-codes 4, 105, 80, 3 or 6.

- `buffer = ReplayBuffer.from_env(stacked_env, DATA_CFG, ENV_CFG)`: one buffer per run. `buffer.steps` is the real-step counter; `collect` refuses to go past `DATA_CFG.budget` (102,400).
- `collect(stacked_env, policy, n_steps, buffer)`: `policy` maps one stack `(k, C, H, W)` uint8 to an int action. Random in iteration 1, the latest PPO policy afterwards.
- **For the world model:** `buffer.sample_batch(B, rng)` returns NumPy `(stack (B,k,C,H,W), action (B,), next_frame (B,C,H,W), reward (B,))`. `to_torch(batch, device)` converts it to float tensors in [0, 1]. Do not train on `split="holdout"`.
- **For PPO:** `buffer.sample_start_states(n, rng)` returns real stacks to start imagined rollouts (about 50 steps each). PPO itself trains on imagined rollouts, not on the buffer.
- **For evaluation:** `buffer.sample_sequences(n, L, rng, split="holdout")` returns start stack, actions `(n,L)`, next frames `(n,L,C,H,W)`, rewards `(n,L)` to measure prediction error vs. rollout length.
- `buffer.save(path)` / `ReplayBuffer.load(path, DATA_CFG, ENV_CFG)`. Loading **refuses** data made with different env settings (game, frame skip, stack, size, sticky actions, reward clipping, pooling), so old files can never silently mix with a new config.
- Only real-game steps go into the buffer. Never add imagined frames. Real-game evaluation for Experiment A must use its own counter, not `collect`.
- Held-out episodes (every 10th) still count toward the 100K budget.
"""