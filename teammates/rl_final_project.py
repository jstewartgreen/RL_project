"""### 2.2 Dataset config and replay buffer
Shapes are read from the environment, not from `DataConfig`, so changing `EnvConfig` changes the dataset automatically. `ReplayBuffer` stores single frames and rebuilds the stacks when sampling; at an episode start the missing older frames repeat the first frame, exactly like `FrameStack.reset()`. Episodes are split into train and held-out by episode.
"""

@dataclass
class DataConfig:
    """Dataset settings. Shapes (stack size, frame size, channels) are NOT set here:
    they are read from the env, so changing EnvConfig automatically changes the dataset."""
    steps_per_iter: int = 6_400      # Sec. 6: 6400 real interactions per loop iteration
    n_iters: int = 16                # 16 x 6400 = 102,400 real steps in total (the budget)
    holdout_every: int = 10          # every 10th episode goes to the held-out split
    extra_slots: int = 2_000         # room for the +1 frame per episode (~120 episodes needed)
    save_dir: str = "data"           # point this at Google Drive in Colab so it survives disconnects
    seed: int = 0

    @property
    def budget(self) -> int:
        return self.steps_per_iter * self.n_iters

    @property
    def capacity(self) -> int:
        return self.budget + self.extra_slots


DATA_CFG = DataConfig()

# EnvConfig fields that change what the data looks like. A saved dataset is only reusable
# if all of these match (seed is allowed to differ).
_DATA_DEFINING = ["game", "frame_skip", "frame_stack", "obs_height", "obs_width",
                  "sticky_action_prob", "clip_rewards", "frame_pool"]


class ReplayBuffer:
    """Dataset D: real transitions only, stored as single frames. Stacks are rebuilt when sampling.

    Each episode occupies T+1 consecutive slots: frames f_0 (reset) ... f_T (last).
    Transition i is (stack ending at f_i, action[i]) -> (f_{i+1}, reward[i]).
    Frames are stored as (C, H, W) uint8; shapes come from the env, not from hard-coded numbers.
    """

    def __init__(self, obs_shape: tuple, n_actions: int, data_cfg: DataConfig, env_meta: dict | None = None):
        k, c, h, w = obs_shape                      # shape of ONE stacked observation
        n = data_cfg.capacity
        self.k, self.cap, self.n_actions = k, n, n_actions
        self.budget = data_cfg.budget
        self.holdout_every = data_cfg.holdout_every
        self.env_meta = env_meta or {}
        self.frames = np.zeros((n, c, h, w), dtype=np.uint8)
        self.action = np.zeros(n, dtype=np.int64)
        self.reward = np.zeros(n, dtype=np.float32)
        self.ep_start = np.zeros(n, dtype=np.int64)   # index of first frame of this frame's episode
        self.has_trans = np.zeros(n, dtype=bool)      # True if an action/next frame exist for slot i
        self.holdout = np.zeros(n, dtype=bool)        # True if the episode is in the held-out split
        self.size = 0          # slots used
        self.steps = 0         # real agent steps taken = the 100K budget counter
        self.n_episodes = 0

    @classmethod
    def from_env(cls, env: gym.Env, data_cfg: DataConfig, env_cfg: "EnvConfig | None" = None):
        """Builds a buffer whose shapes match `env` (must be make_env(stack=True))."""
        shape = env.observation_space.shape
        assert len(shape) == 4, "use make_env(stack=True): expected obs shape (k, C, H, W)"
        meta = asdict(env_cfg) if env_cfg is not None else {}
        return cls(shape, env.action_space.n, data_cfg, meta)

    # ---- writing ----
    def start_episode(self, frame: np.ndarray):
        """frame: (C, H, W) uint8, the first observation after reset."""
        assert self.size < self.cap, "buffer full"
        i = self.size
        self.frames[i] = frame
        self.ep_start[i] = i
        self.holdout[i] = (self.n_episodes % self.holdout_every) == self.holdout_every - 1
        self.size += 1
        self.n_episodes += 1

    def add_step(self, action: int, reward: float, next_frame: np.ndarray):
        """Record the transition out of the latest frame, and the next frame."""
        assert self.size < self.cap, "buffer full"
        assert 0 <= action < self.n_actions, f"bad action {action}"
        i = self.size - 1
        self.action[i], self.reward[i], self.has_trans[i] = action, reward, True
        j = self.size
        self.frames[j] = next_frame
        self.ep_start[j] = self.ep_start[i]
        self.holdout[j] = self.holdout[i]
        self.size += 1
        self.steps += 1

    # ---- reading ----
    def _stack(self, idx: np.ndarray) -> np.ndarray:
        """Stacks ending at idx -> (B, k, C, H, W) and b is batch size. Frames before the episode start
        repeat the first frame, exactly like FrameStack.reset()."""
        offs = idx[:, None] + np.arange(-self.k + 1, 1)[None, :]
        offs = np.maximum(offs, self.ep_start[idx][:, None])
        return self.frames[offs]

    def _valid(self, split: str) -> np.ndarray:
        assert split in ("train", "holdout")
        m = self.has_trans[: self.size]
        h = self.holdout[: self.size]
        return np.flatnonzero(m & (h if split == "holdout" else ~h))

    def sample_batch(self, batch_size: int, rng: np.random.Generator, split: str = "train"):
        """One-step batch: (stack (B,k,C,H,W), action (B,), next_frame (B,C,H,W), reward (B,))."""
        idx = rng.choice(self._valid(split), size=batch_size)
        return self._stack(idx), self.action[idx], self.frames[idx + 1], self.reward[idx]

    def sample_start_states(self, n: int, rng: np.random.Generator, split: str = "train"):
        """Real stacks that start imagined rollouts (Algorithm 1, step 3): (n,k,C,H,W)."""
        idx = rng.choice(self._valid(split), size=n)
        return self._stack(idx)

    def sample_sequences(self, n: int, length: int, rng: np.random.Generator, split: str = "holdout"):
        """Real multi-step sequences for prediction error vs. rollout length.
        Returns start stack (n,k,C,H,W), actions (n,L), next frames (n,L,C,H,W), rewards (n,L)."""
        cand = self._valid(split)
        cand = cand[cand + length - 1 < self.size]
        cand = cand[self.ep_start[cand] == self.ep_start[cand + length - 1]]
        cand = cand[self.has_trans[cand + length - 1]]   # whole window lies inside one episode
        assert len(cand) > 0, "no sequence of this length in the split"
        idx = rng.choice(cand, size=n)
        win = idx[:, None] + np.arange(length)[None, :]
        return self._stack(idx), self.action[win], self.frames[win + 1], self.reward[win]

    def summary(self) -> str:
        r = self.reward[: self.size][self.has_trans[: self.size]]
        mem = self.frames[: self.size].nbytes / 1e9
        return (f"steps={self.steps} episodes={self.n_episodes} slots={self.size}/{self.cap} "
                f"train={len(self._valid('train'))} holdout={len(self._valid('holdout'))} "
                f"rewards(-1/0/+1)={int((r<0).sum())}/{int((r==0).sum())}/{int((r>0).sum())} "
                f"frames={mem:.2f} GB")

    # ---- saving and loading ----
    def save(self, path: str):
        """Saves the used part of the buffer plus the env settings that produced it."""
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        n = self.size
        np.savez_compressed(
            path, frames=self.frames[:n], action=self.action[:n], reward=self.reward[:n],
            ep_start=self.ep_start[:n], has_trans=self.has_trans[:n], holdout=self.holdout[:n],
            counters=np.array([self.steps, self.n_episodes, self.k, self.n_actions]),
            env_meta=np.array(json.dumps(self.env_meta)),
        )

    @classmethod
    def load(cls, path: str, data_cfg: DataConfig, env_cfg: "EnvConfig | None" = None):
        """Loads a saved buffer. Refuses to load data made with different env settings."""
        d = np.load(path, allow_pickle=False)
        saved = json.loads(str(d["env_meta"]))
        if env_cfg is not None and saved:
            now = asdict(env_cfg)
            bad = {k: (saved.get(k), now.get(k)) for k in _DATA_DEFINING if saved.get(k) != now.get(k)}
            assert not bad, f"saved data was made with different env settings (saved, current): {bad}"
        n = len(d["action"])
        _, c, h, w = d["frames"].shape
        steps, n_eps, k, n_actions = (int(x) for x in d["counters"])
        buf = cls((k, c, h, w), n_actions, data_cfg, saved)
        assert n <= buf.cap, "saved data larger than the current capacity; raise DataConfig.n_iters"
        buf.frames[:n], buf.action[:n], buf.reward[:n] = d["frames"], d["action"], d["reward"]
        buf.ep_start[:n], buf.has_trans[:n], buf.holdout[:n] = d["ep_start"], d["has_trans"], d["holdout"]
        buf.size, buf.steps, buf.n_episodes = n, steps, n_eps
        return buf


def to_torch(batch, device="cpu"):
    """Converts a sample_batch result to float tensors scaled to [0, 1] (stacks/frames),
    long actions and float rewards. Torch is imported here so the buffer works without it."""
    import torch
    stack, action, next_frame, reward = batch
    return (torch.from_numpy(stack).to(device).float() / 255.0,
            torch.from_numpy(action).to(device),
            torch.from_numpy(next_frame).to(device).float() / 255.0,
            torch.from_numpy(reward).to(device))

"""### 2.3 Collecting real data
`collect` plays real steps with a policy and writes them to the buffer. It needs the stacked env (the policy takes stacks), but stores only the newest frame of each stack. It stops with an error if it would exceed the 100K budget.
"""

def collect(env: gym.Env, policy, n_steps: int, buffer: ReplayBuffer, seed: int | None = None):
    """Plays `n_steps` real agent steps with `policy` and writes them to `buffer`.

    env must be make_env(cfg, stack=True). policy maps one stack (k, C, H, W) to an int action.
    Refuses to exceed the real-step budget. Returns finished-episode returns (for monitoring).
    """
    assert buffer.steps + n_steps <= buffer.budget, \
        f"would exceed the real-step budget ({buffer.steps}+{n_steps} > {buffer.budget})"
    returns, ep_ret, taken = [], 0.0, 0
    obs, _ = env.reset(seed=seed)
    buffer.start_episode(obs[-1])
    while taken < n_steps:
        a = int(policy(obs))
        obs, r, terminated, truncated, _ = env.step(a)
        buffer.add_step(a, r, obs[-1])
        ep_ret += r
        taken += 1
        if terminated or truncated:
            returns.append(ep_ret)
            ep_ret = 0.0
            if taken < n_steps:
                obs, _ = env.reset()
                buffer.start_episode(obs[-1])
    return returns

