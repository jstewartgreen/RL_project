@dataclass
class EnvConfig:
    """Environment settings. Defaults follow SimPLe."""
    game: str = "ALE/Pong-v5"
    frame_skip: int = 4               # Sec. 6: each action is repeated 4 times
    frame_stack: int = 4              # Sec. 3: model and policy see the last 4 frames
    obs_height: int = 105             # Sec. 6: 210x160 frames downscaled by a factor of 2
    obs_width: int = 80
    sticky_action_prob: float = 0.0   # main results use deterministic actions
    clip_rewards: bool = True         # reward is predicted as one of {-1, 0, 1}
    frame_pool: str = "max"           # "max" over last 2 raw frames, or "last"; not specified in paper
    seed: int = 0


ENV_CFG = EnvConfig()

"""### 1.3 Wrappers
`SimPLeEnv` handles frame skip, pooling, downscaling, and reward clipping. `FrameStack` builds the 4-frame input for a policy.
"""

class SimPLeEnv(gym.Wrapper):
    """Wraps a raw ALE game with SimPLe preprocessing.

    Each step repeats the action `frame_skip` times, sums the rewards,
    pools the last raw frames, and downscales to (obs_height, obs_width).

    Observations are single RGB frames of shape (H, W, 3), dtype uint8.
    """

    def __init__(self, cfg: EnvConfig):
        # frameskip=1 so ALE does not skip on its own; we handle skipping below.
        env = gym.make(
            cfg.game,
            frameskip=1,
            repeat_action_probability=cfg.sticky_action_prob,
        )
        super().__init__(env)
        self.cfg = cfg
        self.observation_space = spaces.Box(
            low=0, high=255, shape=(cfg.obs_height, cfg.obs_width, 3), dtype=np.uint8
        )

    def _process(self, frame: np.ndarray) -> np.ndarray:
        """Downscale a raw (210, 160, 3) frame to (obs_height, obs_width, 3)."""
        # INTER_AREA averages pixel blocks, which keeps small objects like the ball visible.
        return cv2.resize(
            frame, (self.cfg.obs_width, self.cfg.obs_height), interpolation=cv2.INTER_AREA
        )

    def reset(self, **kwargs):
        frame, info = self.env.reset(**kwargs)
        return self._process(frame), info

    def step(self, action: int):
        total_reward = 0.0
        last_two = []  # last 2 raw frames, used for max pooling
        terminated = truncated = False
        info = {}

        for _ in range(self.cfg.frame_skip):
            frame, reward, terminated, truncated, info = self.env.step(action)
            total_reward += reward
            last_two = (last_two + [frame])[-2:]
            if terminated or truncated:
                break

        # Max over the last 2 frames removes flicker where sprites only draw on alternate frames.
        if self.cfg.frame_pool == "max" and len(last_two) == 2:
            pooled = np.maximum(last_two[0], last_two[1])
        else:
            pooled = last_two[-1]

        if self.cfg.clip_rewards:
            total_reward = float(np.sign(total_reward))

        return self._process(pooled), total_reward, terminated, truncated, info

class FrameStack(gym.Wrapper):
    """Stacks the last `k` frames into one observation.

    Observations have shape (k, 3, H, W), dtype uint8, channels first for PyTorch.
    Oldest frame is index 0, newest is index -1.
    """

    def __init__(self, env: gym.Env, k: int):
        super().__init__(env)
        self.k = k
        h, w, c = env.observation_space.shape
        self.frames = np.zeros((k, c, h, w), dtype=np.uint8)
        self.observation_space = spaces.Box(low=0, high=255, shape=(k, c, h, w), dtype=np.uint8)

    def reset(self, **kwargs):
        frame, info = self.env.reset(**kwargs)
        # Fill the stack with the first frame so the observation is valid from step 0.
        self.frames[:] = frame.transpose(2, 0, 1)
        return self.frames.copy(), info

    def step(self, action: int):
        frame, reward, terminated, truncated, info = self.env.step(action)
        self.frames = np.roll(self.frames, shift=-1, axis=0)
        self.frames[-1] = frame.transpose(2, 0, 1)
        return self.frames.copy(), reward, terminated, truncated, info


def make_env(cfg: EnvConfig = ENV_CFG, stack: bool = False) -> gym.Env:
    """Builds the preprocessed env. Use stack=True when feeding a policy."""
    env = SimPLeEnv(cfg)
    if stack:
        env = FrameStack(env, cfg.frame_stack)
    return env

